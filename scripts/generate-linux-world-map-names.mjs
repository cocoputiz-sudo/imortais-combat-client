#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_COMMIT = "585e848493070f2d918f695d0c40fedfe9735ecb";
const SOURCE_DATE = "2026-08-31T11:35:17Z";
const SOURCE_URL =
  "https://raw.githubusercontent.com/ao-data/ao-bin-dumps/" +
  SOURCE_COMMIT +
  "/formatted/world.json";
const EXPECTED_ENTRIES = 1427;

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const outputPath = path.join(
  repoRoot,
  "src",
  "Imortais.LinuxClient",
  "Services",
  "AlbionWorldMapNames.cs"
);

function escapeCSharp(value) {
  return String(value)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n");
}

async function loadWorldJson() {
  const inputArg = process.argv.indexOf("--input");
  if (inputArg >= 0) {
    const inputPath = process.argv[inputArg + 1];
    if (!inputPath) throw new Error("--input requires a JSON path");
    return JSON.parse(await fs.readFile(path.resolve(inputPath), "utf8"));
  }

  const response = await fetch(SOURCE_URL);
  if (!response.ok) {
    throw new Error("world.json download failed: HTTP " + response.status);
  }
  return response.json();
}

const rows = await loadWorldJson();
if (!Array.isArray(rows)) throw new Error("world.json must be an array");

const entries = rows.map((row, i) => {
  const index = String(row?.Index ?? "").trim();
  const uniqueName = String(row?.UniqueName ?? "").trim();
  if (!index || !uniqueName) {
    throw new Error("world.json row " + i + " is missing Index/UniqueName");
  }
  return { index, uniqueName };
});

if (entries.length !== EXPECTED_ENTRIES) {
  throw new Error(
    "unexpected world.json entry count: " +
      entries.length +
      " (expected " +
      EXPECTED_ENTRIES +
      ")"
  );
}

const duplicateCheck = new Set();
for (const entry of entries) {
  const key = entry.index.toLowerCase();
  if (duplicateCheck.has(key)) {
    throw new Error("duplicate world index: " + entry.index);
  }
  duplicateCheck.add(key);
}

const dictionaryLines = entries
  .map(
    ({ index, uniqueName }) =>
      '        ["' +
      escapeCSharp(index) +
      '"] = "' +
      escapeCSharp(uniqueName) +
      '",'
  )
  .join("\n");

const generated = `// <auto-generated>
// Generated by scripts/generate-linux-world-map-names.mjs.
// Source: ao-data/ao-bin-dumps formatted/world.json
// Source commit: ${SOURCE_COMMIT}
// Source date: ${SOURCE_DATE}
// Source URL: ${SOURCE_URL}
// Entries: ${entries.length}
// Do not edit by hand; regenerate with: node scripts/generate-linux-world-map-names.mjs
// </auto-generated>

namespace Imortais.LinuxClient.Services;

public static class AlbionWorldMapNames
{
    private static readonly IReadOnlyDictionary<string, string> Names =
        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
    {
${dictionaryLines}
    };

    public static string Resolve(string? clusterIndex)
    {
        var index = (clusterIndex ?? string.Empty).Trim();
        if (string.IsNullOrEmpty(index)) return "Mapa desconhecido";
        return Names.TryGetValue(index, out var name) && !string.IsNullOrWhiteSpace(name)
            ? name.Trim()
            : index;
    }
}
`;

if (process.argv.includes("--check")) {
  const current = await fs.readFile(outputPath, "utf8");
  if (current !== generated) {
    console.error("AlbionWorldMapNames.cs is out of date.");
    process.exit(1);
  }
  console.log("AlbionWorldMapNames.cs is up to date (" + entries.length + " entries).");
} else {
  await fs.writeFile(outputPath, generated, "utf8");
  console.log("Generated " + outputPath + " with " + entries.length + " entries.");
}
